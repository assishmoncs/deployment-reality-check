const Handlebars = require('handlebars');

const ENV_EXAMPLE_TEMPLATE = `# Generated by Deployment Reality Check (DRC)
# Copy this file to .env and fill in your real credentials. Never commit real secrets.
{{#each variables}}
{{this.name}}={{this.placeholder}}
{{/each}}
`;

const compiledEnvTemplate = Handlebars.compile(ENV_EXAMPLE_TEMPLATE);

export interface EnvTemplateVariable {
  name: string;
  placeholder: string;
}

export function renderEnvExampleTemplate(variables: EnvTemplateVariable[]): string {
  return compiledEnvTemplate({ variables });
}
